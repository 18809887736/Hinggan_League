-- ② 不符项（缺行或带宽不对）——预期 0 行
SELECT e.code, e.lo, e.hi, p.min_limit, p.max_limit
FROM band_exp e LEFT JOIN point_yc p ON p.code = e.code
WHERE p.code IS NULL OR abs(p.min_limit - e.lo) > 1e-9 OR abs(p.max_limit - e.hi) > 1e-9;

-- ③ 清单外却会被补丁⑨纳入正弦的窄带宽点（阈值与补丁一致：0 < max-min <= 1000）
--    预期仅 YC501/YC601/YC901/YC1001（映射锁定功率点，[0,6]/[0,15]，运行时被锁定跳过）
SELECT code, min_limit, max_limit FROM point_yc
WHERE min_limit < max_limit AND max_limit - min_limit <= 1000
  AND code NOT IN (SELECT code FROM band_exp);
